package com.docuvault.shared.storage;

import java.io.IOException;
import java.io.InputStream;
import java.nio.file.Files;
import java.nio.file.NoSuchFileException;
import java.nio.file.Path;
import java.nio.file.StandardCopyOption;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;

/**
 * Writes to a directory on the local filesystem. Development only — a container
 * filesystem does not survive a restart, and two instances would not share it.
 */
public class LocalStorageService implements StorageService {

    private static final Logger log = LoggerFactory.getLogger(LocalStorageService.class);

    private final Path root;

    public LocalStorageService(Path root) {
        this.root = root.toAbsolutePath().normalize();
        try {
            Files.createDirectories(this.root);
        } catch (IOException e) {
            throw new StorageException("Could not create storage directory " + this.root, e);
        }
        log.info("Local file storage active at {}", this.root);
    }

    @Override
    public StoredObject store(InputStream content, String originalFileName, String contentType) {
        String key = StorageKeys.generate(originalFileName);
        Path target = resolve(key);

        try {
            Files.createDirectories(target.getParent());
            // Hash while streaming to disk: the file is never held in memory in
            // full, so a 25 MB upload costs 8 KB of heap rather than 25 MB.
            try (DigestingInputStream digesting = new DigestingInputStream(content)) {
                long bytes = Files.copy(digesting, target, StandardCopyOption.REPLACE_EXISTING);
                return new StoredObject(key, bytes, digesting.checksum());
            }
        } catch (IOException e) {
            throw new StorageException("Failed to store file " + key, e);
        }
    }

    @Override
    public InputStream retrieve(String key) {
        try {
            return Files.newInputStream(resolve(key));
        } catch (NoSuchFileException e) {
            throw new StorageException("Stored file is missing: " + key, e);
        } catch (IOException e) {
            throw new StorageException("Failed to read file " + key, e);
        }
    }

    @Override
    public void delete(String key) {
        try {
            Files.deleteIfExists(resolve(key));
        } catch (IOException e) {
            // A failed cleanup must not fail the user's request; the row is gone
            // either way and an orphaned blob is a reconcilable problem.
            log.warn("Could not delete stored file {}", key, e);
        }
    }

    /**
     * Resolves a key under the storage root and refuses to leave it.
     *
     * <p>Keys are generated by this application, but treating them as untrusted
     * is what keeps a future "download by path" feature from becoming a
     * directory-traversal hole.
     */
    private Path resolve(String key) {
        Path resolved = root.resolve(key).normalize();
        if (!resolved.startsWith(root)) {
            throw new StorageException("Rejected storage key outside the root: " + key);
        }
        return resolved;
    }
}
